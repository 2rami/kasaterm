// Regenerates src/width-table.js from the reference terminal: `vt_oracle widths` feeds every code
// point to alacritty_terminal and reports the cell width it gets.
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { oraclePath } from '../test/oracle.mjs';

const runs = JSON.parse(spawnSync(oraclePath(), ['widths'], { maxBuffer: 1 << 26 }).stdout.toString());
const out = `// Generated by \`vt_oracle widths\` (crates/kasa-pty/examples/vt_oracle.rs): the cell width
// alacritty_terminal gives each code point. Runs of [first, last, width]; width 1 is not listed,
// -1 means the character is dropped. Regenerate with \`node tools/gen-width.mjs\`.
const WIDTH_RUNS = [${runs.flat().join(',')}];
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'width-table.js'), out);
console.log(`${runs.length} runs`);
