#!/usr/bin/env python3
"""Regenerate src/nfc-table.js: every code point that can make NFC change a string.

A string is already NFC when none of its characters has NFC_Quick_Check No or Maybe and none has
a non-zero canonical combining class (that is the Unicode quick-check algorithm with the ordering
test folded in). composeBatch() uses the set to skip decode -> normalize -> encode for text that
NFC would return unchanged, which is most Korean output.

    python3 tools/gen-nfc-table.py
"""
import os
import sys
import unicodedata

flag = set()
for cp in range(0x110000):
    ch = chr(cp)
    if 0xD800 <= cp <= 0xDFFF:
        continue
    if unicodedata.combining(ch):
        flag.add(cp)  # reordering
    if unicodedata.category(ch) == "Cn":
        flag.add(cp)  # unassigned here, maybe a combining mark in the browser's newer Unicode
    if unicodedata.normalize("NFC", ch) != ch:
        flag.add(cp)  # NFC_QC=No: singletons and composition exclusions
    d = unicodedata.decomposition(ch)
    if d and not d.startswith("<"):
        parts = [int(x, 16) for x in d.split()]
        # A primary composite: its second half is NFC_QC=Maybe (may combine with what precedes).
        if len(parts) == 2 and unicodedata.normalize("NFC", unicodedata.normalize("NFD", ch)) == ch:
            flag.add(parts[1])
# Conjoining Hangul jamo, whole blocks (L+V+T compose into syllables).
for a, b in ((0x1100, 0x11FF), (0xA960, 0xA97F), (0xD7B0, 0xD7FF)):
    flag.update(range(a, b + 1))

runs = []
for cp in sorted(flag):
    if runs and runs[-1][1] + 1 == cp:
        runs[-1][1] = cp
    else:
        runs.append([cp, cp])
flat = ",".join(f"{a},{b}" for a, b in runs)
out = (
    "// Code points that can make NFC change a string (NFC_Quick_Check No or Maybe, non-zero combining\n"
    "// class, conjoining Hangul jamo), as [first, last] runs. Generated by tools/gen-nfc-table.py from\n"
    f"// Unicode {unicodedata.unidata_version}.\n"
    f"const NFC_CHECK_RUNS = [{flat}];\n"
)
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "nfc-table.js")
open(path, "w").write(out)
print(f"{len(runs)} runs, {len(flag)} code points, Unicode {unicodedata.unidata_version}", file=sys.stderr)
